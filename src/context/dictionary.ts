/**
 * Intelligent translator:
 * Translates English text to Hindi with strict whole-phrase matching.
 * Never performs partial word splitting on sentences to prevent mixed-language output.
 */
export function translateDynamicEnglishToHindi(text: string): string {
  if (!text || typeof text !== "string") return text;
  const trimmed = text.trim();
  if (!trimmed) return text;

  // 1. Exact phrase match
  if (PHRASE_DICTIONARY[trimmed]) {
    return text.replace(trimmed, PHRASE_DICTIONARY[trimmed]);
  }

  // 2. Trailing punctuation stripped match
  const stripped = trimmed.replace(/^[\s•–—\-\.:]+|[\s•–—\-\.:]+$/g, "");
  if (stripped && PHRASE_DICTIONARY[stripped]) {
    return text.replace(stripped, PHRASE_DICTIONARY[stripped]);
  }

  // 3. For short text or single tokens/badges (<= 3 words)
  const wordCount = trimmed.split(/\s+/).length;
  if (wordCount <= 3) {
    for (const [enKey, hiVal] of SORTED_EN_TO_HINDI) {
      if (enKey.toLowerCase() === trimmed.toLowerCase()) {
        return text.replace(trimmed, hiVal);
      }
    }
  }

  return text;
}

export const HINDI_TO_ENGLISH: Record<string, string> = {};
for (const [en, hi] of Object.entries(PHRASE_DICTIONARY)) {
  if (hi && typeof hi === "string" && hi.trim()) {
    HINDI_TO_ENGLISH[hi.trim()] = en;
  }
}

export const SORTED_HINDI_TO_ENGLISH = Object.entries(HINDI_TO_ENGLISH).sort(
  (a, b) => b[0].length - a[0].length
);

export function translateHindiToEnglish(text: string): string {
  if (!text || typeof text !== "string") return text;
  const trimmed = text.trim();
  if (!trimmed) return text;

  if (HINDI_TO_ENGLISH[trimmed]) {
    return text.replace(trimmed, HINDI_TO_ENGLISH[trimmed]);
  }

  const stripped = trimmed.replace(/^[\s•–—\-\.:]+|[\s•–—\-\.:]+$/g, "");
  if (stripped && HINDI_TO_ENGLISH[stripped]) {
    return text.replace(stripped, HINDI_TO_ENGLISH[stripped]);
  }

  return text;
}
