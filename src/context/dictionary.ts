// Precompute lowercase lookup map for ultra-fast case-insensitive matching
export const LOWERCASE_PHRASE_DICTIONARY: Record<string, string> = {};
for (const [key, val] of Object.entries(PHRASE_DICTIONARY)) {
  LOWERCASE_PHRASE_DICTIONARY[key.toLowerCase()] = val;
}

/**
 * Intelligent dynamic text translator:
 * Detects numbers, units, and translates common English compound phrases into Hindi.
 */
export function translateDynamicEnglishToHindi(text: string): string {
  if (!text || typeof text !== "string") return text;
  const trimmed = text.trim();
  if (!trimmed) return text;

  // 1. Exact phrase match
  if (PHRASE_DICTIONARY[trimmed]) {
    return text.replace(trimmed, PHRASE_DICTIONARY[trimmed]);
  }

  // 2. Lowercase match
  const lower = trimmed.toLowerCase();
  if (LOWERCASE_PHRASE_DICTIONARY[lower]) {
    return text.replace(trimmed, LOWERCASE_PHRASE_DICTIONARY[lower]);
  }

  // 3. Dynamic pattern replacements (e.g. quantities like "45kg", "12 hours", "863 meals")
  let replaced = text;

  // Units
  replaced = replaced
    .replace(/\bkg\b/gi, "कि.ग्रा.")
    .replace(/\btons\b/gi, "टन")
    .replace(/\bmeals\b/gi, "थाली (भोजन)")
    .replace(/\bhours\b/gi, "घंटे")
    .replace(/\bhour\b/gi, "घंटा")
    .replace(/\bmins\b/gi, "मिनट")
    .replace(/\bminutes\b/gi, "मिनट")
    .replace(/\bseconds\b/gi, "सेकंड")
    .replace(/\bdays\b/gi, "दिन");

  // Common status words
  replaced = replaced
    .replace(/\bAt Risk\b/gi, "जोखिम में")
    .replace(/\bSafe\b/gi, "सुरक्षित")
    .replace(/\bCritical\b/gi, "गंभीर")
    .replace(/\bPending\b/gi, "लंबित")
    .replace(/\bCompleted\b/gi, "पूर्ण")
    .replace(/\bVerified\b/gi, "सत्यापित")
    .replace(/\bHigh\b/gi, "उच्च")
    .replace(/\bMedium\b/gi, "मध्यम")
    .replace(/\bLow\b/gi, "निम्न")
    .replace(/\bOnline\b/gi, "ऑनलाइन")
    .replace(/\bOffline\b/gi, "ऑफ़लाइन")
    .replace(/\bActive\b/gi, "सक्रिय");

  // Common keywords (sort by length descending to match longest phrases first)
  const sortedEntries = Object.entries(PHRASE_DICTIONARY).sort(
    (a, b) => b[0].length - a[0].length
  );

  for (const [enKey, hiVal] of sortedEntries) {
    if (enKey.length >= 3 && !/^[0-9\W]+$/.test(enKey)) {
      if (replaced.includes(enKey)) {
        replaced = replaced.split(enKey).join(hiVal);
      }
    }
  }

  return replaced;
}

/**
 * Reverse Dictionary: Hindi to English
 * Allows 100% clean restoration of English when switching back from Hindi.
 */
export const HINDI_TO_ENGLISH: Record<string, string> = {};
for (const [en, hi] of Object.entries(PHRASE_DICTIONARY)) {
  if (hi && typeof hi === "string" && hi.trim()) {
    HINDI_TO_ENGLISH[hi.trim()] = en;
  }
}

// Pre-sorted list of Hindi phrases (longest first)
export const SORTED_HINDI_TO_ENGLISH = Object.entries(HINDI_TO_ENGLISH).sort(
  (a, b) => b[0].length - a[0].length
);

export function isDevanagari(text: string): boolean {
  return /[\u0900-\u097F]/.test(text);
}

/**
 * Intelligent reverse translator:
 * Converts Hindi phrases and text back into English.
 */
export function translateHindiToEnglish(text: string): string {
  if (!text || typeof text !== "string") return text;
  const trimmed = text.trim();
  if (!trimmed) return text;

  // 1. Direct exact match
  if (HINDI_TO_ENGLISH[trimmed]) {
    return text.replace(trimmed, HINDI_TO_ENGLISH[trimmed]);
  }

  // 2. Unit reversals
  let replaced = text
    .replace(/कि\.ग्रा\./g, "kg")
    .replace(/टन/g, "tons")
    .replace(/ग्राम/g, "grams")
    .replace(/थाली \(भोजन\)/g, "meals")
    .replace(/घंटे/g, "hours")
    .replace(/घंटा/g, "hour")
    .replace(/मिनट/g, "mins")
    .replace(/सेकंड/g, "seconds")
    .replace(/दिन/g, "days");

  // 3. Status reversals
  replaced = replaced
    .replace(/जोखिम में/g, "At Risk")
    .replace(/सुरक्षित/g, "Safe")
    .replace(/गंभीर/g, "Critical")
    .replace(/लंबित/g, "Pending")
    .replace(/पूर्ण/g, "Completed")
    .replace(/सत्यापित/g, "Verified")
    .replace(/उच्च/g, "High")
    .replace(/मध्यम/g, "Medium")
    .replace(/निम्न/g, "Low")
    .replace(/ऑनलाइन/g, "Online")
    .replace(/ऑफ़लाइन/g, "Offline")
    .replace(/सक्रिय/g, "Active");

  // 4. Reverse phrase dictionary replacement (longest match first)
  for (const [hiKey, enVal] of SORTED_HINDI_TO_ENGLISH) {
    if (hiKey.length >= 2 && replaced.includes(hiKey)) {
      replaced = replaced.split(hiKey).join(enVal);
    }
  }

  return replaced;
}
